// 약어 (영문 약칭이 제목에 붙은 경우: "1 John" 등은 다루지 않음 — 한글 제목 중심)

function findBooks(title) {
  const t = String(title || '').normalize('NFC');
  const found = new Set();
  for (const [b, re] of BOOK_RES) if (re.test(t)) found.add(b);
  for (const [re, list] of COMBO) if (re.test(t)) for (const b of list) found.add(b);
  // "요한계시록"이 있으면 "요한"만 있는 경우는 이미 제외됨. 로마서 8장 같은 표기는 그대로 유효.
  return BOOKS.filter((b) => found.has(b));
}

