// '롬' (책 전체) · '롬 8' (장) · '롬 8:28' · '롬 8:28-30' · '로마서 8장 28절' → [책, 시작, 끝]
function parseQuery(q) {
  q = String(q || '').trim();
  if (!(/\d/.test(q) || LOOKUP.has(q))) return null;
  const m = /^(.+?)\.?\s*(\d{1,3})?\s*(?:[:：장편]\s*(\d{1,3})?\s*(?:[-–~]\s*(\d{1,3}))?\s*절?)?\s*$/.exec(q);
  if (!m) return null;
  const bid = bookId(m[1].trim()); if (!bid) return null;
  if (!m[2]) return [bid, 0, 999999];
  const c = +m[2]; if (!okCV(bid, c)) return null;
  if (!m[3]) return [bid, pos(c, 0), pos(c, 999)];
  const v1 = +m[3], v2 = m[4] ? +m[4] : v1;
  return [bid, pos(c, v1), pos(c, Math.max(v1, v2))];
}
function label(bid, s, e) {
  const c1 = Math.floor(s / 1000), v1 = s % 1000, c2 = Math.floor(e / 1000), v2 = e % 1000;
  if (s === 0 && e >= 999999) return NAME[bid];
  const unit = bid === 19 ? '편' : '장';
  if (v1 === 0 && v2 === 999) return c1 === c2 ? `${NAME[bid]} ${c1}${unit}` : `${NAME[bid]} ${c1}-${c2}${unit}`;
  if (c1 === c2) return `${NAME[bid]} ${c1}:${v1}` + (v2 !== v1 ? `-${v2}` : '');
  return `${NAME[bid]} ${c1}:${v1}-${c2}:${v2}`;
}
